export default function runProgram(addLog) {

    addLog("Question:");
    addLog("What are Operators in Python?");
    addLog("");

    addLog("Answer:");
    addLog("Operators are special symbols used to perform operations on variables and values.");

    addLog("");

    addLog("Example:");

    let a = 20;
    let b = 10;

    addLog("20 + 10 = " + (a + b));
    addLog("20 - 10 = " + (a - b));
    addLog("20 * 10 = " + (a * b));

    addLog("");

    addLog("Program completed.");

}