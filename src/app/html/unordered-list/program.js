export default function runProgram(addLog) {

    addLog("Question:");
    addLog("What is an Unordered List?");
    addLog("");

    addLog("Answer:");
    addLog("An Unordered List displays items using bullet points.");
    addLog("It is used when the order of items is not important.");
    addLog("");

    addLog("Example:");

    addLog(`<ul>
    <li>HTML</li>
    <li>CSS</li>
    <li>JavaScript</li>
</ul>`);

    addLog("");

    addLog("Output:");
    addLog("• HTML");
    addLog("• CSS");
    addLog("• JavaScript");
    addLog("");

    addLog("Explanation:");
    addLog("<ul> creates an unordered list.");
    addLog("<li> defines each list item.");
    addLog("");

    addLog("Program completed.");

}