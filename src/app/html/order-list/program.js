export default function runProgram(addLog) {

    addLog("Question:");
    addLog("What is an Ordered List?");
    addLog("");

    addLog("Answer:");
    addLog("An Ordered List displays items in a specific order.");
    addLog("By default, the items are numbered.");
    addLog("");

    addLog("Example:");

    addLog(`<ol>
    <li>HTML</li>
    <li>CSS</li>
    <li>JavaScript</li>
</ol>`);

    addLog("");

    addLog("Output:");
    addLog("1. HTML");
    addLog("2. CSS");
    addLog("3. JavaScript");
    addLog("");

    addLog("Explanation:");
    addLog("<ol> creates an ordered list.");
    addLog("<li> defines each list item.");
    addLog("");

    addLog("Program completed.");

}