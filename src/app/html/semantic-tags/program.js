export default function runProgram(addLog) {

    addLog("Question:");
    addLog("What are Semantic Tags?");
    addLog("");

    addLog("Answer:");
    addLog("Semantic tags describe the meaning of the content.");
    addLog("They help browsers, search engines, and developers understand the webpage structure.");
    addLog("");

    addLog("Common Semantic Tags:");
    addLog("- <header>");
    addLog("- <section>");
    addLog("- <article>");
    addLog("- <footer>");
    addLog("");

    addLog("Example:");

    addLog(`<header>
    <h1>My Website</h1>
</header>

<section>
    <article>
        <h2>HTML Tutorial</h2>
        <p>Learning Semantic Tags</p>
    </article>
</section>

<footer>
    Copyright 2026
</footer>`);

    addLog("");

    addLog("Explanation:");
    addLog("<header> defines the top section of the page.");
    addLog("<section> groups related content.");
    addLog("<article> represents independent content.");
    addLog("<footer> defines the bottom section of the page.");
    addLog("");

    addLog("Program completed.");

}