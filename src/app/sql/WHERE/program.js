export default function runProgram(addLog) {

    addLog("Question:");
    addLog("What is WHERE Clause in SQL?");
    addLog("");

    addLog("Answer:");
    addLog("WHERE is used to filter records based on a condition.");

    addLog("");

    addLog("Example:");
    addLog("SELECT * FROM Student WHERE City='Chennai';");

    addLog("");

    addLog("Output:");
    addLog("101 Prasanna 23 Chennai");
    addLog("103 Arun 24 Chennai");

    addLog("");

    addLog("Program completed.");

}