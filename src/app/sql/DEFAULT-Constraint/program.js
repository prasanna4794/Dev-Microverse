export default function runProgram(addLog) {

    addLog("Question:");
    addLog("What is DEFAULT in SQL?");
    addLog("");

    addLog("Answer:");
    addLog("DEFAULT automatically assigns a predefined value if no value is provided.");

    addLog("");

    addLog("Example:");
    addLog("City VARCHAR(50) DEFAULT 'Chennai'");

    addLog("");

    addLog("Output:");
    addLog("City = Chennai");

    addLog("");

    addLog("Program completed.");

}