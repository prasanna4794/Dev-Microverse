export default function runProgram(addLog) {

    addLog("Question:");
    addLog("What is CHECK in SQL?");
    addLog("");

    addLog("Answer:");
    addLog("CHECK validates data based on a specified condition.");

    addLog("");

    addLog("Example:");
    addLog("Age INT CHECK (Age >= 18)");

    addLog("");

    addLog("Output:");
    addLog("Only Age 18 or above is allowed.");

    addLog("");

    addLog("Program completed.");

}