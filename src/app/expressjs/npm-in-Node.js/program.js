export default function runProgram(addLog) {

    addLog("Question:");
    addLog("What is npm in Node.js?");
    addLog("");

    addLog("Answer:");
    addLog(
        "npm stands for Node Package Manager and is used to install and manage Node.js packages."
    );

    addLog("");

    addLog("Example:");
    addLog("npm install express");

    addLog("");

    addLog("Output:");
    addLog("Express package installed successfully.");

    addLog("");

    addLog("Program completed.");
}