export default function runProgram(addLog) {

    addLog("Question:");
    addLog("What is node_modules in Node.js?");
    addLog("");

    addLog("Answer:");
    addLog(
        "node_modules is the folder where installed packages and dependencies are stored."
    );

    addLog("");

    addLog("Example:");
    addLog("npm install express");

    addLog("");

    addLog("Output:");
    addLog("Express package is installed inside node_modules.");

    addLog("");

    addLog("Program completed.");
}