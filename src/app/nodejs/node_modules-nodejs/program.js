export default function runProgram(addLog) {

    addLog("Question:");
    addLog("What is node_modules in Node.js?");
    addLog("");

    addLog("Answer:");
    addLog(
        "node_modules is the folder where npm stores installed packages and dependencies for a Node.js project."
    );

    addLog("");

    addLog("Install Express:");

    addLog("npm install express");

    addLog("");

    addLog("Project Structure:");

    addLog("my-node-app/");
    addLog("├── node_modules/");
    addLog("│   └── express/");
    addLog("├── package.json");
    addLog("├── package-lock.json");
    addLog("└── server.js");

    addLog("");

    addLog("Use Express:");

    addLog('const express = require("express");');

    addLog("");

    addLog("Important:");
    addLog("npm install creates the node_modules folder.");

    addLog("");

    addLog("Program completed.");
}